import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,writeFile,mkdir,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createMahaServer} from '../scripts/dev-server.mjs';

test('the private preview serves site files but blocks repository internals',async()=>{
 const root=await mkdtemp(join(tmpdir(),'maha-preview-test-'));
 const server=createMahaServer({root});
 try{
  await mkdir(join(root,'css'));
  await writeFile(join(root,'css','a.css'),'/* first */ body { color: red; }');
  await writeFile(join(root,'css','b.css'),'/* second */ body { color: blue; }');
  await writeFile(join(root,'index.html'),`<head><link rel="stylesheet" href="./css/a.css"><link rel="stylesheet" href="./css/b.css"></head><h1>MAHA</h1><script type="module" src="./js/main.js"></script>`);
  await writeFile(join(root,'studio.html'),'<h1>Studio</h1>');
  await mkdir(join(root,'content'));
  await writeFile(join(root,'content','today.json'),JSON.stringify(['hello']));
  await mkdir(join(root,'.github'));
  await writeFile(join(root,'.github','secrets.json'),'PRIVATE');
  await mkdir(join(root,'tests'));
  await writeFile(join(root,'tests','hidden.js'),'PRIVATE');
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const base='http://127.0.0.1:'+server.address().port;
  const home=await fetch(base+'/');
  assert.equal(home.status,200);
  const page=await home.text();
  assert.match(page,/MAHA/);
  assert.match(home.headers.get('cache-control'),/private, no-cache/);
  assert.match(page,/css\/maha-preview-bundle\.css/);
  assert.doesNotMatch(page,/\.\/css\/a\.css/);
  assert.doesNotMatch(page,/\.\/css\/b\.css/);
  assert.match(page,/__MAHA_PRIVATE_PREVIEW__/);
  const css=await fetch(base+'/css/maha-preview-bundle.css',{headers:{'Accept-Encoding':'br'}});
  assert.equal(css.status,200);
  assert.equal(css.headers.get('content-encoding'),'br');
  const combined=await css.text();
  assert.ok(combined.indexOf('color: red')<combined.indexOf('color: blue'),'Stylesheet cascade order is unchanged.');
  const cssEtag=css.headers.get('etag');
  assert.ok(cssEtag);
  assert.equal((await fetch(base+'/css/maha-preview-bundle.css',{headers:{'If-None-Match':cssEtag}})).status,304);
  await writeFile(join(root,'css','b.css'),'body { color: green; }');
  const revised=await fetch(base+'/css/maha-preview-bundle.css');
  assert.match(await revised.text(),/color: green/);
  assert.notEqual(revised.headers.get('etag'),cssEtag);
  assert.match(home.headers.get('x-robots-tag'),/noindex/);
  assert.equal((await fetch(base+'/studio.html')).status,200);
  const json=await fetch(base+'/content/today.json');
  assert.equal(json.status,200);
  assert.deepEqual(await json.json(),['hello']);
  assert.equal(json.headers.get('cache-control'),'private, no-cache');
  assert.ok(json.headers.get('etag'));
  assert.equal((await fetch(base+'/content/today.json',{headers:{'If-None-Match':json.headers.get('etag')}})).status,304);
  await writeFile(join(root,'photo.webp'),'fake test photo bytes');
  const photo=await fetch(base+'/photo.webp');
  assert.equal(photo.status,200);
  assert.match(photo.headers.get('cache-control'),/max-age=3600/);
  assert.equal((await fetch(base+'/.github/secrets.json')).status,403);
  assert.equal((await fetch(base+'/tests/hidden.js')).status,403);
  assert.equal((await fetch(base+'/scripts/dev-server.mjs')).status,403);
  assert.equal((await fetch(base+'/nope.txt')).status,404);
  assert.equal((await fetch(base+'/',{method:'POST'})).status,405);
  assert.equal((await fetch(base+'/',{method:'HEAD'})).status,200);
  assert.equal((await fetch(base+'/css/maha-preview-bundle.css',{method:'HEAD'})).status,200);
 }finally{
  await new Promise((resolve,reject)=>server.close(err=>err?reject(err):resolve()));
  await rm(root,{recursive:true,force:true});
 }
});
